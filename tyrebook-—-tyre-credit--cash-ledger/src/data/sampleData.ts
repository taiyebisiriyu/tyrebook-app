import type { TyreBookSnapshot } from '../types/models';

function daysAgoIso(days: number, hour = 10, minute = 15): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

